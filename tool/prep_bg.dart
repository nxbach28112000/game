// Finds where each parallax layer sits inside its full composite scene, and
// writes downscaled copies to assets/images/bg/<world>_<layer>.png plus
// lib/game/bg_layers.dart (offsets in 3840x2160 scene coordinates).
import 'dart:io';
import 'dart:math';
import 'package:image/image.dart';

const worlds = {
  1: ('terrace', 5),
  2: ('throne room', 5),
  3: ('castle', 5),
  4: ('dead forest', 6),
};
const out = 1600; // output width for full-width layers (800px view @ 2x)

void main() {
  final buf = StringBuffer('// GENERATED by tool/prep_bg.dart - do not edit.\n'
      '// world -> list of (file, x, y, w, h) in 3840x2160 scene coordinates,\n'
      '// ordered back to front.\nconst bgLayers = <int, List<(String, double, double, double, double)>>{\n');
  Directory('assets/images/bg').createSync(recursive: true);
  for (final e in worlds.entries) {
    final w = e.key;
    final (name, n) = e.value;
    final comp = decodePng(File('assets/images/backgrounds/$w/$name.png').readAsBytesSync())!;
    const f = 8; // match at 1/8 scale
    final cs = copyResize(comp, width: comp.width ~/ f, interpolation: Interpolation.average);
    buf.writeln('  $w: [');
    // Pixels already explained by the two front layers (they match exactly)
    // are ignored when locating the back layers.
    final covered = List.generate(cs.height, (_) => List.filled(cs.width, false));
    final exact = <int, (int, int)>{};
    for (final k in [1, 2]) {
      final layer = decodePng(File('assets/images/backgrounds/$w/$k.png').readAsBytesSync())!;
      final ls = copyResize(layer, width: max(1, layer.width ~/ 8), interpolation: Interpolation.average);
      var best = double.infinity;
      var bx = 0, by = 0;
      final pts = <(int, int)>[];
      for (var y = 0; y < ls.height; y += 3) {
        for (var x = 0; x < ls.width; x += 3) {
          if (ls.getPixel(x, y).a > 250) pts.add((x, y));
        }
      }
      for (var oy = 0; oy <= cs.height - ls.height; oy++) {
        for (var ox = 0; ox <= cs.width - ls.width; ox++) {
          var d = 0.0;
          for (var i = 0; i < pts.length; i += 2) {
            final (x, y) = pts[i];
            final a = ls.getPixel(x, y), b = cs.getPixel(ox + x, oy + y);
            d += (a.r - b.r).abs() + (a.g - b.g).abs() + (a.b - b.b).abs();
          }
          if (pts.isNotEmpty && d / (pts.length / 2) < best) {
            best = d / (pts.length / 2);
            bx = ox;
            by = oy;
          }
        }
      }
      exact[k] = (bx, by);
      for (var y = 0; y < ls.height; y++) {
        for (var x = 0; x < ls.width; x++) {
          if (ls.getPixel(x, y).a > 20) covered[by + y][bx + x] = true;
        }
      }
    }
    for (var k = n; k >= 1; k--) {
      final layer = decodePng(File('assets/images/backgrounds/$w/$k.png').readAsBytesSync())!;
      final ls = copyResize(layer, width: max(1, layer.width ~/ f), interpolation: Interpolation.average);
      var best = double.infinity;
      var bx = 0, by = 0;
      final maxX = cs.width - ls.width, maxY = cs.height - ls.height;
      // sample opaque pixels
      final pts = <(int, int)>[];
      for (var y = 0; y < ls.height; y += 3) {
        for (var x = 0; x < ls.width; x += 3) {
          if (ls.getPixel(x, y).a > 250) pts.add((x, y));
        }
      }
      if (k > 2) {
        // can't compare where a front layer hides the scene
        pts.removeWhere((p) => false);
      }
      if (pts.isEmpty) {
        stdout.writeln('layer $w/$k has no opaque pixels; placing at 0,0');
      }
      for (var oy = 0; oy <= maxY; oy++) {
        for (var ox = 0; ox <= maxX; ox += (maxX > 0 ? 1 : 1)) {
          var d = 0.0;
          var c = 0;
          for (var i = 0; i < pts.length; i += 2) {
            final (x, y) = pts[i];
            if (k > 2 && covered[oy + y][ox + x]) continue;
            final a = ls.getPixel(x, y), b = cs.getPixel(ox + x, oy + y);
            d += (a.r - b.r).abs() + (a.g - b.g).abs() + (a.b - b.b).abs();
            c++;
          }
          if (c > 20 && d / c < best) {
            best = d / c;
            bx = ox;
            by = oy;
          }
        }
      }
      stdout.writeln('world $w layer $k: ${layer.width}x${layer.height} at (${bx * f}, ${by * f}) err=${best.toStringAsFixed(1)}');
      final file = 'bg/${w}_$k.png';
      final scale = out / 3840;
      final r = copyResize(layer, width: (layer.width * scale).round(), interpolation: Interpolation.average);
      File('assets/images/$file').writeAsBytesSync(encodePng(r));
      buf.writeln("    ('$file', ${bx * f}.0, ${by * f}.0, ${layer.width}.0, ${layer.height}.0),");
    }
    buf.writeln('  ],');
  }
  buf.writeln('};');
  File('lib/game/bg_layers.dart').writeAsStringSync(buf.toString());
}
